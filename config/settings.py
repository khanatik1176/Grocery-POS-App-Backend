# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

# Neon env pull writes a pooled DATABASE_URL for app traffic and a direct
# DATABASE_URL_UNPOOLED for migrations, dumps, and other session commands.
# Django keeps using psycopg. SQLite remains only when neither URL is set.
_DIRECT_COMMANDS = {
    "migrate",
    "makemigrations",
    "flush",
    "dbshell",
    "squashmigrations",
    "dumpdata",
    "loaddata",
}
_pooled_url = os.getenv("DATABASE_URL", "").strip()
_direct_url = os.getenv("DATABASE_URL_UNPOOLED", "").strip()
_use_direct = bool(_direct_url) and any(command in sys.argv for command in _DIRECT_COMMANDS)
_database_url = (_direct_url if _use_direct else _pooled_url) or _direct_url

if "test" in sys.argv:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }
elif _database_url:
    _is_pooled = "-pooler" in _database_url
    DATABASES = {
        "default": dj_database_url.parse(
            _database_url,
            conn_max_age=0 if _is_pooled else 600,
            conn_health_checks=not _is_pooled,
        )
    }
    if _is_pooled:
        # PgBouncer transaction pooling cannot keep server-side cursors
        # or prepared statements across clients.
        DATABASES["default"]["DISABLE_SERVER_SIDE_CURSORS"] = True
        DATABASES["default"].setdefault("OPTIONS", {})
        DATABASES["default"]["OPTIONS"]["prepare_threshold"] = None
else:
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


